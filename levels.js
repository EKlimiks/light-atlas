  const names = { r: 1, g: 2, b: 4, y: 3, m: 5, c: 6, w: 7 };
  const directions = { "^": 0, ">": 1, v: 2, "<": 3 };
  function tokenToTile(token, x, y) {
    const [type, value, extra] = token;
    const shared = { x, y };
    if (type === ".") return { ...shared, type: "empty" };
    if (type === "#") return { ...shared, type: "rock" };
    if (type === "m" || type === "p") return { ...shared, type: type === "m" ? "mirror" : "splitter", value: Number(value), options: 2 };
    if (type === "f") return { ...shared, type: "filter", value: ["r", "g", "b"].indexOf(value), options: 3 };
    if (type === "e") return { ...shared, type: "emitter", mask: names[value], value: Number(extra), options: 4 };
    if (type === "d") return { ...shared, type: "dock", group: value, angle: extra === undefined ? null : Number(extra) };
    if (type === "k") return { ...shared, type: "spectral", mask: names[value], value: Number(extra), options: 2 };
    if (type === "a" || type === "q") return { ...shared, type: "polar", value: Number(value), options: type === "a" ? 2 : 0 };
    if (type === "s" || type === "g") return { ...shared, type: type === "s" ? "sensor" : "gate", group: value };
    if (type === "t") return { ...shared, type: "target", mask: names[value] };
    return { ...shared, type: "source", mask: names[value], direction: directions[type] };
  }

